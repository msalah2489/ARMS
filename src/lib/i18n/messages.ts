export function translate(locale: AppLocale, key: MessageKey): string {
  if (locale === "en") return messagesEn[key] ?? messagesAr[key] ?? key;
  return messagesAr[key] ?? key;
}

export function statusMessageKey(value: string): MessageKey | null {
  const key = `status.${value}` as MessageKey;
  return key in messagesAr ? key : null;
}
